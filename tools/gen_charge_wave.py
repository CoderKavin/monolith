"""Generates the charging wave: for each battery level (2% steps) an animated vector whose wavy
arc flows forward, plus a one-view layout so the widget can pick the right one. Same geometry as
Gfx.wavyRing: 200-unit box, radius 82, amplitude 3.2, 11 waves, stroke 11, starting at 12 o'clock.
Run from the repo root: python3 tools/gen_charge_wave.py"""
import math, os

R0, AMP, WAVES, STROKE = 82.0, 3.2, 11, 11
KEYS = 8            # phases per cycle (the last equals the first, so it loops seamlessly)
STEP_DEG = 7.5      # sampling along the arc
TAPER_DEG = 10.0    # wave eases to zero at the ends so the round caps sit still
OUT_D = 'app/src/main/res/drawable'
OUT_L = 'app/src/main/res/layout'

def f(v): return ('%.2f' % v).rstrip('0').rstrip('.')

def path(level, phase):
    t0 = -math.pi / 2
    span = 2 * math.pi * level / 100.0
    n = max(4, int(round(math.degrees(span) / STEP_DEG)))
    taper = min(math.radians(TAPER_DEG), span / 3)
    pts = []
    for i in range(n + 1):
        a = t0 + span * i / n
        d = min(a - t0, t0 + span - a)
        env = 1.0 if d >= taper else (0.5 - 0.5 * math.cos(math.pi * d / taper))
        r = R0 + AMP * env * math.sin(WAVES * (a - t0) - phase)
        pts.append((100 + r * math.cos(a), 100 + r * math.sin(a)))
    # Catmull-Rom to cubic Beziers: smooth, and the same commands for every phase (so it can morph).
    out = 'M%s,%s' % (f(pts[0][0]), f(pts[0][1]))
    for i in range(len(pts) - 1):
        p0 = pts[max(0, i - 1)]; p1 = pts[i]; p2 = pts[i + 1]; p3 = pts[min(len(pts) - 1, i + 2)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out += 'C%s,%s %s,%s %s,%s' % (f(c1[0]), f(c1[1]), f(c2[0]), f(c2[1]), f(p2[0]), f(p2[1]))
    return out

FRAMES = 30   # wave positions per cycle; the ProgressBar sweeps through them like a flipbook

def vector(d):
    return ('<vector android:width="200dp" android:height="200dp" android:viewportWidth="200" android:viewportHeight="200">'
            '<path android:pathData="%s" android:strokeColor="#FFFFFFFF" android:strokeWidth="%d" '
            'android:strokeLineCap="round" android:strokeLineJoin="round" /></vector>' % (d, STROKE))

for level in range(4, 101, 4):
    items = []
    for k in range(FRAMES):
        lo = round(k * 10000 / FRAMES); hi = round((k + 1) * 10000 / FRAMES) - 1 if k < FRAMES - 1 else 10000
        items.append('    <item android:minLevel="%d" android:maxLevel="%d">%s</item>' % (lo, hi, vector(path(level, 2 * math.pi * k / FRAMES))))
    xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_charge_wave.py: charging wave at %d%%, one still drawing per wave position.
     An indeterminate ProgressBar sweeps the level 0..10000 and so flips through them. -->
<level-list xmlns:android="http://schemas.android.com/apk/res/android">
%s
</level-list>
""" % (level, '\n'.join(items))
    open(os.path.join(OUT_D, 'charge_wave_%d.xml' % level), 'w').write(xml)
    lay = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_charge_wave.py. -->
<ProgressBar xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/wave"
    android:layout_width="120dp"
    android:layout_height="120dp"
    android:layout_gravity="center"
    android:indeterminate="true"
    android:indeterminateBehavior="repeat"
    android:indeterminateDuration="1600"
    android:indeterminateDrawable="@drawable/charge_wave_%d"
    android:indeterminateTint="@color/g_on_primary_c"
    android:indeterminateTintMode="src_in" />
""" % level
    open(os.path.join(OUT_L, 'wave_%d.xml' % level), 'w').write(lay)
print('ok')
